def res(p):
    if not p.is_file():
        return None
    try:
        return json.loads(p.read_text().strip().splitlines()[-1])
    except Exception:
        return {"result": "unreadable"}


def wcount(n):
    p = FS / "weights" / "rows" / f"{n}.csv"
    if not p.is_file():
        return "0"
    rr = list(csv.DictReader(open(p, newline="")))
    return f"{len(rr)} files, {sum(int(r['bytes']) for r in rr) / 1e6:.1f} MB (weights/rows/{n}.csv)"


